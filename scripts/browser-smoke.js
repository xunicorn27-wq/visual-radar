// Run in a dedicated Playwright CLI session; see docs/浏览器验收.md.
async (page) => {
  const base = "http://127.0.0.1:3210/visual-radar/";
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const errors = []; const onError = (error) => errors.push(error.message);
  page.on("pageerror", onError);
  try {
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base + "issues");
    await page.getByRole("searchbox", { name: "搜索往期内容" }).fill("tao");
    await page.getByRole("status").filter({ hasText: "找到 1 条内容" }).waitFor();
    await page.getByRole("combobox", { name: "日报月份" }).selectOption("2026-10");
    await page.getByRole("combobox", { name: "内容排序" }).selectOption("oldest");
    const result = page.locator("article.vr-archive-card").first();
    const resultId = await result.getAttribute("id");
    await result.getByRole("button", { name: /^编辑备注：/ }).click();
    const dialog = page.locator("dialog[open]");
    await dialog.getByRole("textbox").fill("浏览器验收：侧光与纹理（本次编辑）");
    await page.keyboard.press("Escape");
    await dialog.getByText("这次修改尚未保存。").waitFor();
    await dialog.getByRole("button", { name: "继续编辑" }).click();
    await dialog.getByRole("textbox").fill("浏览器验收：侧光与纹理（自动回归）");
    await dialog.getByRole("button", { name: "保存备注" }).click();
    await dialog.waitFor({ state: "hidden" });
    const request = result.locator("a.vr-archive-card-link");
    await request.click();
    await page.getByRole("heading", { name: "摄影推送", exact: true }).waitFor();
    await page.waitForFunction(() => document.activeElement?.id === location.hash.slice(1));
    await page.getByRole("link", { name: "返回浏览结果" }).click();
    await page.waitForFunction((id) => document.activeElement?.id === id, resultId);
    assert(new URL(page.url()).searchParams.get("q") === "tao", "返回未保留搜索");
    assert(await page.getByRole("combobox", { name: "日报月份" }).inputValue() === "2026-10", "返回未保留月份");
    await page.getByRole("link", { name: "我的收藏", exact: true }).click();
    await page.getByText("浏览器验收：侧光与纹理（自动回归）", { exact: true }).waitFor();
    await page.reload();
    await page.getByText("浏览器验收：侧光与纹理（自动回归）", { exact: true }).waitFor();
    await page.getByRole("searchbox", { name: "搜索收藏与备注" }).fill("自动回归");
    await page.getByRole("status").filter({ hasText: "找到 1 条收藏" }).waitFor();
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "导出当前结果（含备注）" }).click();
    const download = await downloadPromise;
    assert(download.suggestedFilename().endsWith(".md"), "导出格式错误");
    await download.saveAs("output/playwright/collection-test.md");
    await page.screenshot({ path: "output/playwright/saved-desktop.png" });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "手机页横向溢出");
    const nav = page.getByRole("navigation", { name: "Visual Radar 主导航" });
    assert(await nav.evaluate((el) => getComputedStyle(el).position === "fixed"), "手机导航未固定");
    await page.screenshot({ path: "output/playwright/saved-mobile.png" });
    await page.getByRole("link", { name: "今日日报", exact: true }).click();
    await page.getByRole("heading", { name: "摄影推送", exact: true }).waitFor();
    await page.screenshot({ path: "output/playwright/home-mobile.png" });
    const imageButton = page.getByRole("button", { name: /^查看完整图片：/ }).first();
    await imageButton.click();
    await page.locator("dialog[open]").waitFor();
    await page.keyboard.press("Escape");
    await page.locator("dialog[open]").waitFor({ state: "hidden" });
    await page.goto(base);
    await page.getByRole("heading", { name: "摄影推送", exact: true }).waitFor();
    await page.keyboard.press("Tab");
    assert(await page.getByRole("link", { name: "跳到主要内容" }).evaluate((el) => document.activeElement === el), "跳转入口未首先获得焦点");
    await page.keyboard.press("Enter");
    assert(await page.evaluate(() => document.activeElement?.id === "main-content"), "未聚焦主要内容");
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: "output/playwright/home-desktop.png" });
    assert(errors.length === 0, errors.join("\n"));
    return { passed: true, browser: "firefox", checks: ["搜索与月份", "备注关闭保护", "保存与刷新恢复", "返回搜索位置", "Markdown下载", "手机无溢出与底栏", "全图弹窗Escape", "键盘跳转"], screenshots: "output/playwright/" };
  } finally { page.off("pageerror", onError); }
}
